import { pgTable, text, serial, timestamp, integer, numeric, boolean } from "drizzle-orm/pg-core";
import { createInsertSchema } from "drizzle-zod";
import { z } from "zod/v4";
import { customersTable } from "./customers";
import { employeesTable } from "./employees";

// طلب تسعير العميل — Customer Request for Quotation
export const customerRfqsTable = pgTable("customer_rfqs", {
  id: serial("id").primaryKey(),
  internalNo: text("internal_no").notNull().unique(),
  customerId: integer("customer_id").references(() => customersTable.id),
  customerName: text("customer_name").notNull(),
  customerRfqNo: text("customer_rfq_no").notNull(),
  numberAutoGenerated: boolean("number_auto_generated").notNull().default(false),
  entryDate: text("entry_date"),
  expiryDate: text("expiry_date"),
  buyerName: text("buyer_name"),
  // Employee who entered the RFQ (auto from session, like supplier rfq).
  employeeId: integer("employee_id").references(() => employeesTable.id),
  employeeName: text("employee_name"),
  status: text("status").notNull().default("draft"),
  notes: text("notes"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true })
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date()),
});

export const customerRfqItemsTable = pgTable("customer_rfq_items", {
  id: serial("id").primaryKey(),
  customerRfqId: integer("customer_rfq_id")
    .notNull()
    .references(() => customerRfqsTable.id, { onDelete: "cascade" }),
  partNo: text("part_no"),
  lineItem: text("line_item"),
  description: text("description"),
  uom: text("uom"),
  qty: numeric("qty", { precision: 15, scale: 4 }),
  unitPrice: numeric("unit_price", { precision: 15, scale: 4 }),
  // Item category (تصنيف البند). Plain integer; DB FK added in init-db.ts.
  categoryId: integer("category_id"),
  // ── AI classification analysis (تحليل التصنيف) ────────────────────────────
  // The classifier's multi-dimensional read of the item, stored so the manager
  // can review the SUGGESTION beside the decision (the operator's requirement:
  // «مراجعة اقتراحات الذكاء الاصطناعي وتعديلها»). `categoryId` stays the
  // authoritative PRIMARY functional domain; `brandId`/`subcategoryIds` never
  // affect responsibility. Plain columns; DDL lives in init-db.ts.
  brandId: integer("brand_id"),
  subcategoryIds: text("subcategory_ids"),
  technicalAttributes: text("technical_attributes"),
  classifyConfidence: numeric("classify_confidence", { precision: 5, scale: 2 }),
  classifyReason: text("classify_reason"),
  // Review suggestion for an item left unclassified (cleanup of a retired category).
  // Never applied on its own: a manager accepts it by choosing the category.
  suggestedCategoryId: integer("suggested_category_id"),
  // Soft-cancel: an item is disabled, never hard-deleted (its assignment
  // history must survive). Plain boolean; DDL lives in init-db.ts.
  isCancelled: boolean("is_cancelled").notNull().default(false),
  // ── Attribution (تثبيت الإنجاز) ──────────────────────────────────────────
  // Set at the FIRST customer PO linked to this item, even when no employee is
  // responsible (employee_id stays null → "غير محسوم" and is never re-attributed
  // later). The name is a SNAPSHOT so historical reports survive a rename.
  attributionFirstPoAt: timestamp("attribution_first_po_at", { withTimezone: true }),
  attributionEmployeeId: integer("attribution_employee_id"),
  attributionEmployeeName: text("attribution_employee_name"),
  attributionEvent: text("attribution_event"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

export const insertCustomerRfqSchema = createInsertSchema(customerRfqsTable).omit({
  id: true,
  createdAt: true,
  updatedAt: true,
});
export type InsertCustomerRfq = z.infer<typeof insertCustomerRfqSchema>;
export type CustomerRfq = typeof customerRfqsTable.$inferSelect;

export const insertCustomerRfqItemSchema = createInsertSchema(customerRfqItemsTable).omit({
  id: true,
  createdAt: true,
});
export type InsertCustomerRfqItem = z.infer<typeof insertCustomerRfqItemSchema>;
export type CustomerRfqItem = typeof customerRfqItemsTable.$inferSelect;
